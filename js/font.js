function textW(s, sc) { return s.length ? (s.length * 6 - 1) * (sc || 1) : 0; }

function drawText(g, s, x, y, color, sc) {
  sc = sc || 1;
  g.fillStyle = color;
  s = String(s).toUpperCase();
  for (var i = 0; i < s.length; i++) {
    var rows = FONT[s[i]] || FONT[' '];
    for (var r = 0; r < 7; r++) {
      for (var c = 0; c < 5; c++) {
        if ((rows[r] >> (4 - c)) & 1) g.fillRect(x + (i * 6 + c) * sc, y + r * sc, sc, sc);
      }
    }
  }
}
