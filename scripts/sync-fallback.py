#!/usr/bin/env python3
"""Regenerate js/content-fallback.js (inline copy used when fetch of data/content.json fails) from data/content.json."""
import json
items=json.load(open('data/content.json'))
open('js/content-fallback.js','w').write('// GENERATED by scripts/sync-fallback.py from data/content.json. Do not edit by hand.\nvar FALLBACK_CONTENT = '+json.dumps(items,ensure_ascii=False)+';\n')
print(len(items))
